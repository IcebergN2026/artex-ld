/**
 * export-formats.ts：拓扑图导出为 GraphML 1.0（yEd/Gephi 可读）与 draw.io mxGraph XML。
 * 职责：把拓扑图序列化为 GraphML / draw.io XML 文本。
 * 主要函数/类型：
 *   - exportGraphML：导出 GraphML 1.0 文本（分组以 group_ref 关联的扁平结构）
 *   - exportDrawIO：导出 draw.io mxGraph XML 文本（未压缩明文，一图一页）
 * 纯函数、确定性输出（固定头注释、无时间戳）、无浏览器 API，可在 node 中单测。
 */

import type { TopologyGraph, TopologyGraphGroup, TopologyGraphNode } from "@/lib/types";

import { EDGE_KIND_META, groupSize, NODE_H, NODE_W } from "./graph-model";

const GRAPHML_COMMENT = "Generated by artex-ld topology export (GraphML 1.0). Do not edit by hand.";
const DRAWIO_COMMENT = "Generated by artex-ld topology export (draw.io mxGraph XML). Do not edit by hand.";

const DRAWIO_GROUP_STYLE =
  "rounded=0;whiteSpace=wrap;html=1;container=1;collapsible=0;dashed=1;dashPattern=3 3;" +
  "fillColor=none;strokeColor=#666666;align=left;verticalAlign=top;fontSize=12;spacingLeft=4;spacingTop=2;";
const DRAWIO_NODE_STYLE_BASE =
  "rounded=1;arcSize=8;whiteSpace=wrap;html=1;fillColor=#ffffff;fontSize=12;align=center;verticalAlign=middle;";
const DRAWIO_EDGE_STYLE_BASE = "rounded=0;html=1;jettySize=auto;strokeWidth=1.5;";

/** 节点/分组 id 前缀（mxGraph 把 id 当普通字符串，冒号合法）。 */
const groupCellId = (group: TopologyGraphGroup): string => `g:${group.name}`;
const nodeCellId = (ip: string): string => `n:${ip}`;

/** XML 转义五个特殊字符：& < > " '。 */
function xmlEscape(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** 画布置色在并行迭代中以可选字段挂在节点/边上；老数据可能没有。 */
function ownColor(item: unknown): string {
  const color = (item as { color?: unknown } | null | undefined)?.color;
  return typeof color === "string" ? color.trim() : "";
}

/** 坐标输出统一保留两位小数，避免 1e-7 之类浮点噪声。 */
function fmtNum(n: number): string {
  return String(Math.round(n * 100) / 100);
}

/** 节点的画布绝对坐标：分组内相对分组框左上角，框外即绝对坐标。 */
function absolutePosition(node: TopologyGraphNode, groups: TopologyGraphGroup[]): { x: number; y: number } {
  if (node.group_id == null) return { x: node.x, y: node.y };
  const group = groups.find((g) => g.id === node.group_id);
  if (!group) return { x: node.x, y: node.y };
  return { x: group.x + node.x, y: group.y + node.y };
}

// GraphML 1.0（扁平结构：分组也是普通节点，成员节点用 group_ref 关联）

const GRAPHML_NODE_KEYS: Array<{ id: string; name: string }> = [
  { id: "d_label", name: "label" },
  { id: "d_hostname", name: "hostname" },
  { id: "d_ip", name: "ip" },
  { id: "d_entry_status", name: "entry_status" },
  { id: "d_color", name: "color" },
  { id: "d_is_group", name: "is_group" },
  { id: "d_x", name: "x" },
  { id: "d_y", name: "y" },
  { id: "d_width", name: "width" },
  { id: "d_height", name: "height" },
  { id: "d_group_ref", name: "group_ref" },
];

const GRAPHML_EDGE_KEYS: Array<{ id: string; name: string }> = [
  { id: "d_elabel", name: "label" },
  { id: "d_kind", name: "kind" },
  { id: "d_ecolor", name: "color" },
  { id: "d_evidence", name: "evidence" },
];

function graphMLData(keyId: string, value: string): string {
  return `<data key="${keyId}">${xmlEscape(value)}</data>`;
}

function graphMLNode(id: string, data: string[]): string {
  return `      <node id="${xmlEscape(id)}">\n${data.map((d) => `        ${d}`).join("\n")}\n      </node>`;
}

export function exportGraphML(graph: TopologyGraph): string {
  const lines: string[] = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push(`<!-- ${GRAPHML_COMMENT} -->`);
  lines.push('<graphml xmlns="http://graphml.graphdrawing.org/xmlns">');
  for (const key of GRAPHML_NODE_KEYS) {
    lines.push(`  <key id="${key.id}" for="node" attr.name="${key.name}" attr.type="string"/>`);
  }
  for (const key of GRAPHML_EDGE_KEYS) {
    lines.push(`  <key id="${key.id}" for="edge" attr.name="${key.name}" attr.type="string"/>`);
  }
  lines.push('  <graph edgedefault="directed">');

  // 分组先输出：本身是 is_group=true 的节点，携带几何信息。
  for (const group of graph.groups) {
    const size = groupSize(group);
    const color = ownColor(group);
    lines.push(
      graphMLNode(group.name, [
        graphMLData("d_label", group.name),
        graphMLData("d_is_group", "true"),
        graphMLData("d_x", fmtNum(group.x)),
        graphMLData("d_y", fmtNum(group.y)),
        graphMLData("d_width", fmtNum(size.width)),
        graphMLData("d_height", fmtNum(size.height)),
        ...(color ? [graphMLData("d_color", color)] : []),
      ]),
    );
  }

  for (const node of graph.nodes) {
    const color = ownColor(node);
    const memberGroup = node.group_id == null ? null : (graph.groups.find((g) => g.id === node.group_id) ?? null);
    lines.push(
      graphMLNode(node.ip, [
        graphMLData("d_label", node.display_label || node.hostname || node.ip),
        graphMLData("d_hostname", node.hostname),
        graphMLData("d_ip", node.ip),
        graphMLData("d_entry_status", node.entry_status),
        ...(color ? [graphMLData("d_color", color)] : []),
        graphMLData("d_is_group", "false"),
        graphMLData("d_x", fmtNum(node.x)),
        graphMLData("d_y", fmtNum(node.y)),
        ...(memberGroup ? [graphMLData("d_group_ref", memberGroup.name)] : []),
      ]),
    );
  }

  graph.edges.forEach((edge, index) => {
    const color = ownColor(edge);
    lines.push(`      <edge id="e${index}" source="${xmlEscape(edge.src_ip)}" target="${xmlEscape(edge.dst_ip)}">`);
    lines.push(`        ${graphMLData("d_elabel", edge.label)}`);
    lines.push(`        ${graphMLData("d_kind", edge.kind)}`);
    if (color) lines.push(`        ${graphMLData("d_ecolor", color)}`);
    lines.push(`        ${graphMLData("d_evidence", edge.evidence_ref)}`);
    lines.push("      </edge>");
  });

  lines.push("  </graph>");
  lines.push("</graphml>");
  lines.push("");
  return lines.join("\n");
}

// draw.io mxGraph XML（未压缩明文，一图一页）

function mxGeometry(x: number, y: number, width: number, height: number): string {
  return `<mxGeometry x="${fmtNum(x)}" y="${fmtNum(y)}" width="${fmtNum(width)}" height="${fmtNum(height)}" as="geometry"/>`;
}

/** html=1 标签：换行先转成 <br> 再整体转义，draw.io 会解码回 <br> 渲染换行。 */
function drawioValue(text: string): string {
  return xmlEscape(text.replace(/\r?\n/g, "<br>"));
}

export function exportDrawIO(graph: TopologyGraph): string {
  const cells: string[] = [];

  for (const group of graph.groups) {
    const size = groupSize(group);
    cells.push(
      `        <mxCell id="${xmlEscape(groupCellId(group))}" value="${xmlEscape(group.name)}" ` +
        `style="${DRAWIO_GROUP_STYLE}" vertex="1" parent="1">`,
    );
    cells.push(`          ${mxGeometry(group.x, group.y, size.width, size.height)}`);
    cells.push("        </mxCell>");
  }

  for (const node of graph.nodes) {
    const memberGroup = node.group_id == null ? null : (graph.groups.find((g) => g.id === node.group_id) ?? null);
    const abs = absolutePosition(node, graph.groups);
    const stroke = ownColor(node) || "#666666";
    const fontStyle = node.entry_status === "confirmed" ? "fontStyle=1;" : "";
    const style = `${DRAWIO_NODE_STYLE_BASE}strokeColor=${stroke};${fontStyle}`;
    const parent = memberGroup ? groupCellId(memberGroup) : "1";
    const label = node.display_label || node.hostname || node.ip;
    cells.push(
      `        <mxCell id="${xmlEscape(nodeCellId(node.ip))}" value="${drawioValue(label)}" ` +
        `style="${style}" vertex="1" parent="${xmlEscape(parent)}">`,
    );
    cells.push(`          ${mxGeometry(abs.x, abs.y, NODE_W, NODE_H)}`);
    cells.push("        </mxCell>");
  }

  graph.edges.forEach((edge, index) => {
    const meta = EDGE_KIND_META[edge.kind];
    const stroke = ownColor(edge) || meta.stroke;
    const dashed = meta.dash ? "1" : "0";
    const style = `${DRAWIO_EDGE_STYLE_BASE}strokeColor=${stroke};dashed=${dashed};`;
    const value = drawioValue(edge.label);
    cells.push(
      `        <mxCell id="e${index}" value="${value}" style="${style}" edge="1" parent="1" ` +
        `source="${xmlEscape(nodeCellId(edge.src_ip))}" target="${xmlEscape(nodeCellId(edge.dst_ip))}">`,
    );
    cells.push('          <mxGeometry relative="1" as="geometry"/>');
    cells.push("        </mxCell>");
  });

  const lines: string[] = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push(`<!-- ${DRAWIO_COMMENT} -->`);
  lines.push('<mxfile host="artex" type="device">');
  lines.push('  <diagram name="内网拓扑" id="artex-topology">');
  lines.push(
    '    <mxGraphModel dx="800" dy="600" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" ' +
      'arrows="1" fold="1" page="1" pageScale="1" pageWidth="850" pageHeight="1100" math="0" shadow="0">',
  );
  lines.push("      <root>");
  lines.push('        <mxCell id="0"/>');
  lines.push('        <mxCell id="1" parent="0"/>');
  lines.push(cells.join("\n"));
  lines.push("      </root>");
  lines.push("    </mxGraphModel>");
  lines.push("  </diagram>");
  lines.push("</mxfile>");
  lines.push("");
  return lines.join("\n");
}
